"""Render the hand-edited inputs into every generated artifact.

A blueprint directory mixes the two on purpose, because it is the unit
a host fetches at a tag and a reader opens:

  blueprints/<id>/docker-compose.yml  HAND-EDITED; the swarm stack file a host deploys with
                                      docker stack deploy. Generated by
                                      pack_all (lib/pack.py) from services.yml, x-catena.yml
                                      and the script files under hooks/ when the folder
                                      holds services.yml
  blueprints/<id>/app.json            HAND-EDITED; the card and catalog data of the app
  blueprints/<id>/logo.png            HAND-PLACED; optional
  blueprints/<id>/logo.svg            generated placeholder, absent a logo.png

At the repo root, everything is generated:

  catalog.json                        the browsable catalog: every template with its prose
  index.html                          static catalog preview

`catalog.json` carries the SSO mode, the compose's x-catena block (env, quiesce
and lifecycle commands, object-store check), bench membership, sizing, and the
bilingual prose. Neither generated file is hand-edited.

Idempotency is the contract: rendering twice produces byte-identical
output, and CI fails the PR when the committed artifacts drift.
"""
from __future__ import annotations

import hashlib
import html
import json
import re
import shutil
from pathlib import Path
from typing import Any

from .model import BLUEPRINTS, ROOT, Entry, load_meta, load_sources
from .pack import PackError, pack_all

CATALOG_JSON = ROOT / "catalog.json"
INDEX_HTML = ROOT / "index.html"

# Matches a generated secret's lookup expression, with or without a filter
# (`... | lower`).
LOOKUP_PASSWORD_RE = re.compile(
    r"\{\{\s*lookup\(\s*['\"]password['\"]\s*,\s*['\"]/dev/null\s+length=(\d+)[^'\"]*['\"]\s*\)"
    r"(?:\s*\|[^}]*?)?\s*\}\}"
)

# How the gallery, the detail panel and the preview name an entry the registry
# importer wrote and no person has finished.
IMPORTED_MARK = "Imported, untested"


def requires_sentence(entry: Entry) -> str:
    """The release sentence of an entry that needs a newer Catena, else empty."""
    if not entry.requires_catena:
        return ""
    return f"Requires Catena {entry.requires_catena} or later."


def render_catalog_entry(entry: Entry) -> dict[str, Any]:
    """The flat machine view. Key names match what the consumers join
    on; the nesting in app.json exists for the human editing it. The
    compose block's env, lifecycle, quiesce and object_store
    pass through unchanged, and its managed env keys become env_managed_keys.
    env_defaults is the env as KEY=value lines. An imported entry's status,
    origin and null stubs pass through too."""
    cat = entry.catena
    bench = cat["bench"]
    out: dict[str, Any] = {
        "id": entry.slug,
        "app_name": cat["app_name"],
        "upstream_url": cat["upstream_url"],
        "sso_mode": cat["sso_mode"],
        **{f"domain_{part}": value for part, value in cat.get("domain", {}).items()},
        "compose_file": entry.compose_file,
        "env_defaults": entry.env_defaults,
        "bench_pack": bench["pack"],
        "bench_fixture": bench.get("fixture", "required"),
        "hostname_baked": bench.get("hostname_baked", False),
        "categories": list(entry.raw["categories"]),
        "sizing": dict(cat["sizing"]),
        "en": cat["en"],
        "fr": cat["fr"],
    }
    if entry.imported:
        out["status"] = cat["status"]
    if entry.origin:
        out["origin"] = dict(entry.origin)
    if entry.requires_catena:
        out["requires_catena"] = entry.requires_catena
    out["env"] = entry.env
    if entry.managed_env:
        out["env_managed_keys"] = list(entry.managed_env)
    if entry.object_store:
        out["object_store"] = entry.object_store
    if entry.lifecycle:
        out["lifecycle"] = entry.lifecycle
    if entry.quiesce:
        out["quiesce"] = entry.quiesce
    return out


# Deterministic placeholder-logo palette, indexed by hash(slug). Picked to
# stay legible on light and dark backgrounds.
_LOGO_PALETTE: tuple[tuple[str, str], ...] = (
    ("#0f766e", "#ffffff"),
    ("#1d4ed8", "#ffffff"),
    ("#7c3aed", "#ffffff"),
    ("#be123c", "#ffffff"),
    ("#c2410c", "#ffffff"),
    ("#65a30d", "#ffffff"),
    ("#0284c7", "#ffffff"),
    ("#a16207", "#ffffff"),
)


def placeholder_logo_svg(slug: str, label: str) -> str:
    digest = hashlib.sha256(slug.encode("utf-8")).digest()
    bg, fg = _LOGO_PALETTE[digest[0] % len(_LOGO_PALETTE)]
    glyph = (label or slug or "?")[0].upper()
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">'
        f'<rect width="256" height="256" rx="32" fill="{bg}"/>'
        f'<text x="128" y="128" text-anchor="middle" dominant-baseline="central" '
        f'font-family="system-ui,-apple-system,Segoe UI,Roboto,sans-serif" '
        f'font-size="148" font-weight="600" fill="{fg}">{glyph}</text>'
        '</svg>\n'
    )


def resolve_logo(entry: Entry) -> str:
    """Return the logo filename inside the blueprint directory.

    A hand-placed `logo.png` wins and is left alone. Without one the
    render writes a deterministic `logo.svg` placeholder, and drops a
    placeholder left over from before a real logo arrived."""
    out_dir = entry.app_dir
    placeholder = out_dir / "logo.svg"
    if (out_dir / "logo.png").exists():
        placeholder.unlink(missing_ok=True)
        return "logo.png"
    label = entry.prose("en")["display_name"]
    placeholder.write_text(placeholder_logo_svg(entry.slug, label))
    return "logo.svg"


def render_index_html(entries: list[Entry], meta: dict[str, Any]) -> str:
    """A static preview of the catalog. No build step, no external
    assets: it is opened straight from the repo or served by the
    Dockerfile alongside catalog.json."""
    rows = []
    for entry in entries:
        en = entry.prose("en")
        cats = ", ".join(entry.raw["categories"])
        name = en["display_name"]
        if entry.imported:
            name = f"{name} ({IMPORTED_MARK.lower()})"
        what = " ".join(s for s in (requires_sentence(entry), en["what_it_is"]) if s)
        rows.append(
            "      <tr>"
            f"<td><code>{html.escape(entry.slug)}</code></td>"
            f"<td>{html.escape(name)}</td>"
            f"<td>{html.escape(what)}</td>"
            f"<td>{html.escape(cats)}</td>"
            f"<td>{html.escape(entry.catena['sso_mode'])}</td>"
            f"<td><a href=\"{html.escape(entry.catena['upstream_url'])}\">upstream</a></td>"
            "</tr>"
        )
    return (
        "<!doctype html>\n"
        '<html lang="en">\n'
        "<head>\n"
        '  <meta charset="utf-8">\n'
        '  <meta name="viewport" content="width=device-width, initial-scale=1">\n'
        "  <title>Catena template catalog</title>\n"
        "  <style>\n"
        "    :root { color-scheme: light dark; }\n"
        "    body { font-family: system-ui, sans-serif; margin: 2rem auto; max-width: 70rem; padding: 0 1rem; }\n"
        "    table { border-collapse: collapse; width: 100%; }\n"
        "    th, td { border-bottom: 1px solid #8883; padding: 0.4rem 0.6rem; text-align: left; vertical-align: top; }\n"
        "    code { font-size: 0.9em; }\n"
        "    caption { text-align: left; padding-bottom: 0.8rem; color: #8889; }\n"
        "  </style>\n"
        "</head>\n"
        "<body>\n"
        "  <h1>Catena template catalog</h1>\n"
        f"  <p>{len(entries)} templates. Generated from each app's metadata file; do not edit.</p>\n"
        "  <table>\n"
        f"    <caption>Sizing measured on {html.escape(meta['sizing']['measurement_host'])}, "
        f"last {html.escape(meta['sizing']['last_measured_at'])}.</caption>\n"
        "    <thead><tr><th>id</th><th>Name</th><th>What it is</th>"
        "<th>Categories</th><th>SSO</th><th>Upstream</th></tr></thead>\n"
        "    <tbody>\n"
        + "\n".join(rows)
        + "\n    </tbody>\n"
        "  </table>\n"
        "</body>\n"
        "</html>\n"
    )


def _prune_orphan_blueprints(entries: list[Entry]) -> list[str]:
    """Drop blueprint directories no app.json claims.

    The render cannot simply wipe `blueprints/` and rebuild it: the
    compose in each directory is hand-edited, and so is any logo.png
    beside it. Deleting a whole directory is therefore the one
    destructive act here, and it happens only when the folder has no
    app.json."""
    if not BLUEPRINTS.is_dir():
        return []
    live = {entry.slug for entry in entries}
    dropped = []
    for path in sorted(BLUEPRINTS.iterdir()):
        if path.is_dir() and path.name not in live:
            shutil.rmtree(path)
            dropped.append(path.name)
    return dropped


def render_all() -> int:
    try:
        packed = pack_all()
    except PackError as exc:
        print(f"pack: {exc}")
        return 1
    entries = load_sources()
    meta = load_meta()

    BLUEPRINTS.mkdir(parents=True, exist_ok=True)
    dropped = _prune_orphan_blueprints(entries)

    catalog_entries: list[dict[str, Any]] = []
    for entry in entries:
        resolve_logo(entry)
        catalog_entries.append(render_catalog_entry(entry))

    CATALOG_JSON.write_text(
        json.dumps(
            {
                "version": 1,
                "sizing": meta["sizing"],
                "templates": catalog_entries,
            },
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )
    INDEX_HTML.write_text(render_index_html(entries, meta))

    print(
        f"rendered {len(entries)} templates: a logo per "
        f"blueprint, plus catalog.json + index.html"
    )
    if packed:
        print(f"packed {len(packed)} compose file(s) from neat files")
    if dropped:
        print(f"dropped {len(dropped)} blueprint(s) with no app.json: "
              f"{', '.join(dropped)}")
    return 0
